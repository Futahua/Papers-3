import { spawn } from 'node:child_process';
import * as fs from 'node:fs';
import * as crypto from 'node:crypto';

const AHK = 'C:\\Program Files\\AutoHotkey\\v2\\AutoHotkey64.exe';
const SCRIPT = 'D:\\333\\SlopTop\\sloptop_engine.ahk';
const SHARED = 'C:\\Users\\Public\\Documents\\PapersNativeBridgeReceipts';
const PW = 'C:\\Program Files\\PowerShell\\7\\pwsh.exe';
const token = crypto.randomUUID();
const receipt = `${SHARED}\\startup-${token}.receipt`;
fs.mkdirSync(SHARED, { recursive: true });
const before = new Set(fs.readdirSync(SHARED));
const quote = (value) => `'${String(value).replaceAll("'", "''")}'`;
const launchCommand = `$p=Start-Process -FilePath ${quote(AHK)} -ArgumentList @('/force',${quote(SCRIPT)},${quote(receipt)},${quote(token)},'startup-diagnostic') -Verb RunAs -PassThru; $p.Id`;
const child = spawn(PW, ['-NoProfile', '-NonInteractive', '-Command', launchCommand], { windowsHide: true, stdio: ['ignore', 'pipe', 'pipe'] });
const launcherOutput = [];
child.stdout.on('data', (chunk) => launcherOutput.push(String(chunk)));
child.stderr.on('data', (chunk) => launcherOutput.push(String(chunk)));
const output = [];
child.stdout.on('data', (chunk) => output.push(String(chunk)));
child.stderr.on('data', (chunk) => output.push(String(chunk)));
const deadline = Date.now() + 10000;
while (Date.now() < deadline && !fs.existsSync(receipt) && child.exitCode === null) await new Promise((resolve) => setTimeout(resolve, 100));
const after = fs.existsSync(receipt) ? fs.readFileSync(receipt, 'utf8') : '';
const childExit = child.exitCode;
console.log(JSON.stringify({ token, receipt, launcherPid: child.pid, elevatedPid: Number(launcherOutput.join('').trim()), childExit, receipt: after, output: output.join(''), launcherOutput: launcherOutput.join(''), preexisting: [...before] }));
if (child.exitCode === null) child.kill();
if (fs.existsSync(receipt)) fs.rmSync(receipt, { force: true });
process.exitCode = after.includes(`"token":"${token}"`) && /"pid":\d+/.test(after) ? 0 : 1;
